def test_anzhela_maliarevych_find_nb():
    """Test find_nb for anzhela_maliarevych_find_nb"""
    assert anzhela_maliarevych_find_nb.find_nb(4) == -1
    assert anzhela_maliarevych_find_nb.find_nb(16) == -1
    assert anzhela_maliarevych_find_nb.find_nb(4183059834009) == 2022
    assert anzhela_maliarevych_find_nb.find_nb(24723578342962) == -1
    assert anzhela_maliarevych_find_nb.find_nb(135440716410000) == 4824
    assert anzhela_maliarevych_find_nb.find_nb(40539911473216) == 3568
